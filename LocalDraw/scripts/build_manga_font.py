"""Embed the licensed comic font in the self-contained SVG renderer.

Development-only dependency: fonttools.
Run after replacing the source TTF; the app needs neither package at runtime.
"""
import base64
import gzip
import json
from pathlib import Path

from fontTools.ttLib import TTFont
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.recordingPen import DecomposingRecordingPen

ROOT = Path(__file__).resolve().parents[1]
FONT = ROOT / "web/fonts/lxgw-marker-gothic"
font = TTFont(FONT / "LXGWMarkerGothic-Regular.ttf", recalcTimestamp=False)
glyph_set = font.getGlyphSet()
paths = {}
for codepoint, name in font.getBestCmap().items():
    recording = DecomposingRecordingPen(glyph_set)
    glyph_set[name].draw(recording)
    pen = SVGPathPen(None, ntos=lambda v: str(round(v, 1)).removesuffix('.0'))
    recording.replay(pen)
    paths[chr(codepoint)] = [glyph_set[name].width, pen.getCommands()]
payload = json.dumps({'units': font['head'].unitsPerEm, 'glyphs': paths}, ensure_ascii=False, separators=(',', ':')).encode()
encoded = base64.b64encode(gzip.compress(payload, mtime=0)).decode("ascii")
license_text = (FONT / "OFL.txt").read_text(encoding="utf-8")
target = ROOT / "web/drawing.js"
source = target.read_text(encoding="utf-8")
start = source.index("  // BEGIN EMBEDDED MANGA FONT")
end = source.index("  // END EMBEDDED MANGA FONT", start)
replacement = (
    "  // BEGIN EMBEDDED MANGA FONT (generated by scripts/build_manga_font.py)\n"
    f"  const mangaFont = {json.dumps(encoded)};\n"
    f"  const mangaFontLicense = {json.dumps(license_text)};\n"
)
target.write_text(source[:start] + replacement + source[end:], encoding="utf-8")
print(f"Embedded {len(paths):,} glyph outlines: {len(encoded):,} encoded bytes")
